package com.crossnotify.app.service

import android.app.Notification
import android.service.notification.NotificationListenerService
import android.service.notification.StatusBarNotification
import com.crossnotify.app.data.repository.CrossNotifyRepository
import dagger.hilt.android.AndroidEntryPoint
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.cancel
import kotlinx.coroutines.launch
import java.util.concurrent.ConcurrentHashMap
import javax.inject.Inject

/**
 * Intercepts incoming system notifications on the relay device:
 * - Filters out ongoing/foreground-service alerts, group summaries, empty notifications,
 *   and notifications generated by CrossNotify itself to prevent feedback loops.
 * - Deduplicates frequent updates using a 10-second sliding window per channel and notification content.
 * - Encrypts qualifying notifications with AES-256-GCM and persists them to the local outbox.
 */
@AndroidEntryPoint
class CrossNotifyListenerService : NotificationListenerService() {

    @Inject
    lateinit var repository: CrossNotifyRepository

    private val serviceScope = CoroutineScope(SupervisorJob() + Dispatchers.IO)

    private data class DedupeKey(
        val channelId: String,
        val sbnKey: String,
        val contentHash: Int
    )

    private val recentNotifications = ConcurrentHashMap<DedupeKey, Long>()

    companion object {
        private const val DEDUPE_WINDOW_MS = 10_000L
    }

    override fun onNotificationPosted(sbn: StatusBarNotification?) {
        val posted = sbn ?: return
        val pkg = posted.packageName ?: return

        // 1. Always ignore CrossNotify's own package so locally displayed notifications are never re-captured
        if (pkg == applicationContext.packageName) return

        val notification = posted.notification ?: return
        val flags = notification.flags

        // 2. Skip ongoing, foreground service, and group summary notifications
        if (posted.isOngoing) return
        if ((flags and Notification.FLAG_ONGOING_EVENT) != 0) return
        if ((flags and Notification.FLAG_FOREGROUND_SERVICE) != 0) return
        if ((flags and Notification.FLAG_GROUP_SUMMARY) != 0) return

        // Ignore system UI / media / progress-only noise without meaningful text
        val extras = notification.extras ?: return
        val title = extras.getCharSequence(Notification.EXTRA_TITLE)?.toString()?.trim().orEmpty()
        val text = extras.getCharSequence(Notification.EXTRA_TEXT)?.toString()?.trim().orEmpty()
        val bigText = extras.getCharSequence(Notification.EXTRA_BIG_TEXT)?.toString()?.trim().orEmpty()
        val subText = extras.getCharSequence(Notification.EXTRA_SUB_TEXT)?.toString()?.trim().orEmpty()

        val effectiveText = text.ifEmpty { bigText }
        if (title.isEmpty() && effectiveText.isEmpty()) return

        val appLabel = resolveAppLabel(pkg)
        val category = notification.category.orEmpty()
        val postedAt = if (posted.postTime > 0) posted.postTime else System.currentTimeMillis()
        val sbnKey = posted.key ?: "$pkg:${posted.id}"
        val contentHash = "$title|$effectiveText|$bigText".hashCode()

        serviceScope.launch {
            pruneDedupeCache()
            repository.captureAndQueueNotification(
                packageName = pkg,
                appLabel = appLabel,
                title = title,
                text = effectiveText,
                subText = subText,
                bigText = bigText,
                category = category,
                postedAt = postedAt,
                shouldSendForChannel = { channelId ->
                    val now = System.currentTimeMillis()
                    val dedupeKey = DedupeKey(channelId, sbnKey, contentHash)
                    val previousSentAt = recentNotifications[dedupeKey]
                    if (previousSentAt != null && (now - previousSentAt) < DEDUPE_WINDOW_MS) {
                        false
                    } else {
                        recentNotifications[dedupeKey] = now
                        true
                    }
                }
            )
        }
    }

    private fun resolveAppLabel(packageName: String): String {
        return runCatching {
            val pm = applicationContext.packageManager
            val appInfo = pm.getApplicationInfo(packageName, 0)
            pm.getApplicationLabel(appInfo).toString()
        }.getOrDefault(packageName)
    }

    private fun pruneDedupeCache() {
        val cutoff = System.currentTimeMillis() - DEDUPE_WINDOW_MS * 3
        val iterator = recentNotifications.entries.iterator()
        while (iterator.hasNext()) {
            val entry = iterator.next()
            if (entry.value < cutoff) {
                iterator.remove()
            }
        }
    }

    override fun onDestroy() {
        serviceScope.cancel()
        super.onDestroy()
    }
}
