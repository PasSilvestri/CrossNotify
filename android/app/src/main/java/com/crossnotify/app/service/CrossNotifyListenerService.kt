package com.crossnotify.app.service

import android.app.Notification
import android.os.Build
import android.service.notification.NotificationListenerService
import android.service.notification.StatusBarNotification
import com.crossnotify.app.crypto.NotificationActionMeta
import com.crossnotify.app.data.api.DismissNotificationItem
import com.crossnotify.app.data.repository.CrossNotifyRepository
import com.crossnotify.app.util.AppIconHelper
import com.crossnotify.app.util.NotificationMediaHelper
import dagger.hilt.android.AndroidEntryPoint
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.Job
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.cancel
import kotlinx.coroutines.delay
import kotlinx.coroutines.launch
import java.util.concurrent.ConcurrentHashMap
import javax.inject.Inject

/**
 * Intercepts incoming system notifications and removals on the relay device:
 * - Filters out ongoing/foreground-service alerts, group summaries, empty notifications,
 *   and notifications generated by CrossNotify itself to prevent feedback loops.
 * - Extracts forwardable notification actions (inline RemoteInput replies & background actions)
 *   and attached media images.
 * - Deduplicates frequent updates using a 10-second sliding window per channel and notification content.
 * - Debounces notification removals over a 400ms window and batches dismissal events to the server.
 */
@AndroidEntryPoint
class CrossNotifyListenerService : NotificationListenerService() {

    @Inject
    lateinit var repository: CrossNotifyRepository

    @Inject
    lateinit var registry: RelayNotificationRegistry

    private val serviceScope = CoroutineScope(SupervisorJob() + Dispatchers.IO)

    private data class DedupeKey(
        val channelId: String,
        val sbnKey: String,
        val contentHash: Int
    )

    private val recentNotifications = ConcurrentHashMap<DedupeKey, Long>()
    private val pendingDismissalsLock = Any()
    private val pendingDismissalsByChannel = HashMap<String, MutableList<DismissNotificationItem>>()
    private var dismissFlushJob: Job? = null

    companion object {
        private const val DEDUPE_WINDOW_MS = 10_000L
        private const val DISMISS_DEBOUNCE_MS = 400L
    }

    override fun onCreate() {
        super.onCreate()
        registry.setCancelCallback { sbnKey ->
            runCatching { cancelNotification(sbnKey) }
        }
    }

    override fun onListenerConnected() {
        super.onListenerConnected()
        registry.setCancelCallback { sbnKey ->
            runCatching { cancelNotification(sbnKey) }
        }
    }

    override fun onNotificationPosted(sbn: StatusBarNotification?) {
        val posted = sbn ?: return
        val pkg = posted.packageName ?: return

        // 1. Always ignore CrossNotify's own package so locally displayed notifications are never re-captured
        if (pkg == applicationContext.packageName) return

        val notification = posted.notification ?: return
        val flags = notification.flags

        // 2. Skip ongoing, foreground service, and group summary notifications
        if (posted.isOngoing) return
        if ((flags and Notification.FLAG_ONGOING_EVENT) != 0) return
        if ((flags and Notification.FLAG_FOREGROUND_SERVICE) != 0) return
        if ((flags and Notification.FLAG_GROUP_SUMMARY) != 0) return

        // Ignore system UI / media / progress-only noise without meaningful text
        val extras = notification.extras ?: return
        val title = extras.getCharSequence(Notification.EXTRA_TITLE)?.toString()?.trim().orEmpty()
        val text = extras.getCharSequence(Notification.EXTRA_TEXT)?.toString()?.trim().orEmpty()
        val bigText = extras.getCharSequence(Notification.EXTRA_BIG_TEXT)?.toString()?.trim().orEmpty()
        val subText = extras.getCharSequence(Notification.EXTRA_SUB_TEXT)?.toString()?.trim().orEmpty()

        val effectiveText = text.ifEmpty { bigText }
        val imageBase64 = NotificationMediaHelper.extractNotificationImageBase64(applicationContext, notification)
        if (title.isEmpty() && effectiveText.isEmpty() && imageBase64.isNullOrEmpty()) return

        val appLabel = resolveAppLabel(pkg)
        val appIconBase64 = AppIconHelper.getAppIconBase64(applicationContext, pkg)
        val category = notification.category.orEmpty()
        val postedAt = if (posted.postTime > 0) posted.postTime else System.currentTimeMillis()
        val sbnKey = posted.key ?: "$pkg:${posted.id}"
        val contentHash = "$title|$effectiveText|$bigText|${imageBase64?.hashCode() ?: 0}".hashCode()

        // Extract forwardable actions (RemoteInput inline replies + background Broadcast/Service actions)
        val (actionsMeta, rawActions) = extractForwardableActions(notification)

        serviceScope.launch {
            pruneDedupeCache()
            repository.captureAndQueueNotification(
                packageName = pkg,
                appLabel = appLabel,
                appIconBase64 = appIconBase64,
                imageBase64 = imageBase64,
                title = title,
                text = effectiveText,
                subText = subText,
                bigText = bigText,
                category = category,
                postedAt = postedAt,
                sbnKey = sbnKey,
                actionsMeta = actionsMeta,
                rawActions = rawActions,
                shouldSendForChannel = { channelId ->
                    val now = System.currentTimeMillis()
                    val dedupeKey = DedupeKey(channelId, sbnKey, contentHash)
                    val previousSentAt = recentNotifications[dedupeKey]
                    if (previousSentAt != null && (now - previousSentAt) < DEDUPE_WINDOW_MS) {
                        false
                    } else {
                        recentNotifications[dedupeKey] = now
                        true
                    }
                }
            )
        }
    }

    override fun onNotificationRemoved(
        sbn: StatusBarNotification?,
        rankingMap: RankingMap?,
        reason: Int
    ) {
        val removed = sbn ?: return
        val sbnKey = removed.key ?: "${removed.packageName}:${removed.id}"

        // Only emit dismissals for notifications that were actually relayed
        val tracked = registry.consumeBySbnKey(sbnKey)
        if (tracked.isEmpty()) return

        val dismissReason = when (reason) {
            REASON_CLICK -> "opened"
            else -> "dismissed"
        }

        synchronized(pendingDismissalsLock) {
            for ((channelId, notificationId) in tracked) {
                val list = pendingDismissalsByChannel.getOrPut(channelId) { mutableListOf() }
                list.add(DismissNotificationItem(notificationId = notificationId, reason = dismissReason))
            }
            dismissFlushJob?.cancel()
            dismissFlushJob = serviceScope.launch {
                delay(DISMISS_DEBOUNCE_MS)
                flushPendingDismissals()
            }
        }
    }

    override fun onNotificationRemoved(sbn: StatusBarNotification?) {
        onNotificationRemoved(sbn, null, REASON_CANCEL)
    }

    private suspend fun flushPendingDismissals() {
        val snapshot: Map<String, List<DismissNotificationItem>> = synchronized(pendingDismissalsLock) {
            if (pendingDismissalsByChannel.isEmpty()) return
            val copy = pendingDismissalsByChannel.mapValues { it.value.toList() }
            pendingDismissalsByChannel.clear()
            copy
        }

        for ((channelId, items) in snapshot) {
            if (items.isNotEmpty()) {
                repository.dispatchDismissalsBatch(channelId, items)
            }
        }
    }

    private fun extractForwardableActions(
        notification: Notification
    ): Pair<List<NotificationActionMeta>, List<Notification.Action>> {
        val sourceActions = notification.actions ?: return emptyList<NotificationActionMeta>() to emptyList()
        val metas = mutableListOf<NotificationActionMeta>()
        val raw = mutableListOf<Notification.Action>()

        for (action in sourceActions) {
            val pi = action.actionIntent ?: continue
            val actionTitle = action.title?.toString()?.trim().orEmpty()
            if (actionTitle.isBlank()) continue

            val remoteInputs = action.remoteInputs
            val hasRemoteInput = !remoteInputs.isNullOrEmpty()

            // On Android 12+ (API 31+), filter out pure Activity-launching actions that
            // Background Activity Launch (BAL) restrictions would block from background execution.
            if (!hasRemoteInput && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S) {
                val isActivityIntent = runCatching { pi.isActivity }.getOrDefault(false)
                if (isActivityIntent) continue
            }

            val firstRi = remoteInputs?.firstOrNull()
            val replyLabel = firstRi?.label?.toString()?.trim()?.takeIf { it.isNotBlank() }
            val choices = firstRi?.choices
                ?.mapNotNull { it?.toString()?.trim()?.takeIf { s -> s.isNotBlank() } }
                ?.take(5)
                .orEmpty()

            val idx = raw.size
            raw.add(action)
            metas.add(
                NotificationActionMeta(
                    idx = idx,
                    title = actionTitle,
                    isReply = hasRemoteInput,
                    replyLabel = replyLabel,
                    choices = choices
                )
            )
            if (raw.size >= 5) break
        }

        return metas to raw
    }

    private fun resolveAppLabel(packageName: String): String {
        return runCatching {
            val pm = applicationContext.packageManager
            val appInfo = pm.getApplicationInfo(packageName, 0)
            pm.getApplicationLabel(appInfo).toString()
        }.getOrDefault(packageName)
    }

    private fun pruneDedupeCache() {
        val cutoff = System.currentTimeMillis() - DEDUPE_WINDOW_MS * 3
        val iterator = recentNotifications.entries.iterator()
        while (iterator.hasNext()) {
            val entry = iterator.next()
            if (entry.value < cutoff) {
                iterator.remove()
            }
        }
    }

    override fun onDestroy() {
        registry.setCancelCallback(null)
        serviceScope.cancel()
        super.onDestroy()
    }
}
